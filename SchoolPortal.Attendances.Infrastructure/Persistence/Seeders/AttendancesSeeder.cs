using SchoolPortal.Attendances.Application.Directories;
using SchoolPortal.Attendances.Application.Persistence;
using SchoolPortal.Attendances.Domain.Attendances;
using SchoolPortal.Attendances.Domain.SessionOccurrences;
using SchoolPortal.Attendances.Domain.Sessions;
using SchoolPortal.SharedKernel.Persistence.Seeders;

namespace SchoolPortal.Attendances.Infrastructure.Persistence.Seeders;

internal sealed class AttendancesSeeder(
    ISessionDirectory sessions,
    ISessionOccurrenceDirectory occurrences,
    IAttendanceDirectory attendances,
    IAttendancesUnitOfWork unitOfWork,
    TimeProvider clock) : IDataSeeder
{
    public int Order => 50;

    // WHY relative to today: fixed dates would go stale; recent weeks always give
    // the history view something to show.
    private const int DaysBack = 28;

    public async Task SeedAsync(CancellationToken ct)
    {
        var sectionA = SeedConstants.FullyEnrolledSectionIds[0];
        var sectionB = SeedConstants.FullyEnrolledSectionIds[1];

        // WHY this as the guard: it's an existing directory method, so no new
        // interface member is needed just to ask "is there anything yet?".
        if ((await sessions.GetByCourseSectionAsync(sectionA, ct)).Count > 0)
            return;

        var templates = new (int SectionId, DayOfWeek Day, TimeOnly Start, TimeOnly End)[]
        {
            (sectionA, DayOfWeek.Sunday, new TimeOnly(9, 0), new TimeOnly(10, 30)),
            (sectionA, DayOfWeek.Monday, new TimeOnly(9, 0), new TimeOnly(10, 30)),
            (sectionA, DayOfWeek.Wednesday, new TimeOnly(9, 0), new TimeOnly(10, 30)),
            (sectionB, DayOfWeek.Sunday, new TimeOnly(11, 0), new TimeOnly(12, 30)),
            (sectionB, DayOfWeek.Tuesday, new TimeOnly(11, 0), new TimeOnly(12, 30)),
            (sectionB, DayOfWeek.Thursday, new TimeOnly(11, 0), new TimeOnly(12, 30))
        };

        var sessionList = templates.Select(t => Session.Create(t.SectionId, t.Day, t.Start, t.End).Unwrap("session"))
            .ToList();

        foreach (var session in sessionList)
            sessions.Add(session);

        // Session.Id is generated by the DB and occurrences need it.
        await unitOfWork.SaveChangesAsync(ct);

        // WHY local date (same as the /today endpoint): with UTC, the seeder and the
        // endpoint disagree about "today" for a few hours after midnight in Egypt.
        var today = DateOnly.FromDateTime(clock.GetLocalNow().DateTime);
        var occurrenceList = new List<SessionOccurrence>();

        foreach (var session in sessionList)
            for (var offset = 0; offset < DaysBack; offset++)
            {
                var date = today.AddDays(-offset);

                // A "Monday" session only happens on Mondays.
                if (date.DayOfWeek != session.DayOfWeek)
                    continue;

                occurrenceList.Add(SessionOccurrence.Create(session.Id, date).Unwrap("occurrence"));
            }

        foreach (var occurrence in occurrenceList)
            occurrences.Add(occurrence);

        await unitOfWork.SaveChangesAsync(ct);

        var rng = new Random(42);

        foreach (var occurrence in occurrenceList)
        foreach (var studentId in SeedConstants.StudentIds)
        {
            var status = PickStatus(rng);
            attendances.Add(Attendance.Create(studentId, occurrence.Id, status, NoteFor(status)).Unwrap("attendance"));
        }

        await unitOfWork.SaveChangesAsync(ct);
    }

    // WHY weighted: real classes are mostly present; a uniform split looks fake.
    private static AttendanceStatus PickStatus(Random rng) =>
        rng.Next(100) switch
        {
            < 70 => AttendanceStatus.Present,
            < 80 => AttendanceStatus.Late,
            < 90 => AttendanceStatus.Absent,
            < 95 => AttendanceStatus.Excused,
            _ => AttendanceStatus.EarlyLeave
        };

    private static string? NoteFor(AttendanceStatus status) =>
        status switch
        {
            AttendanceStatus.Late => "Arrived after the session started",
            AttendanceStatus.Absent => "No reason given",
            AttendanceStatus.Excused => "Excused by the office",
            AttendanceStatus.EarlyLeave => "Left before the session ended",
            _ => null
        };
}